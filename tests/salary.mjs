import assert from 'node:assert/strict';
import {salaryEstimate,weekdays,serviceYears,SCALES} from '../docs/salary.mjs';
assert.equal(weekdays('2026-09'),22);assert.equal(weekdays('2026-10'),22);assert.equal(weekdays('2024-02'),21);
assert.equal(serviceYears('2020-09-30','2026-09-29'),5);assert.equal(serviceYears('2020-09-30','2026-09-30'),6);
assert.throws(()=>serviceYears('2026-02-30','2026-10-03'));
const params={month:'2026-09',category:1,hireDate:'2020-09-30',today:'2026-10-03',netMinutes:90,saturdayMinutes:120,lateCount:4,earlyCount:3,hasAttendance:true};
const r=salaryEstimate(params);
assert.equal(r.base,1268726.58);assert.equal(r.presentism,317181.65);assert.equal(r.extra,14417.35);assert.equal(r.saturdays,25630.84);assert.equal(r.seniority,89305.62);assert.equal(r.total,1715262.04);
assert.equal(salaryEstimate({...params,lateCount:5}).presentism,0);
assert.equal(salaryEstimate({...params,earlyCount:4}).presentism,0);
assert.equal(salaryEstimate({...params,lateCount:4,earlyCount:3}).eligible,true);
assert.equal(salaryEstimate({...params,netMinutes:-90}).extra,-9611.56);
assert.equal(salaryEstimate({...params,hasAttendance:false}).presentism,0);
assert.equal(salaryEstimate({...params,hasAttendance:false}).extra,0);
assert.equal(salaryEstimate({...params,month:'2026-10'}).scaleMonth,'2026-09');
assert.equal(salaryEstimate({...params,month:'2026-08'}).rate,6300.6);
assert.throws(()=>salaryEstimate({...params,month:'2026-06'}));
assert.throws(()=>salaryEstimate({...params,category:11}));
assert.throws(()=>salaryEstimate({...params,hireDate:'2027-01-01'}));
for(const s of SCALES)for(let c=1;c<=10;c++)assert.ok(s.hourly[c]>0);
console.log('Salary checks passed: weekdays, source month, all categories, presentism thresholds, signed balance, Saturdays, service years and missing attendance.');
